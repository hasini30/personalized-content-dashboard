export class MockTranslator implements Translator {
  public name = 'MockTranslator';
  private shouldSimulateFailure = false;
  private cache: TranslationCache;

  constructor(cache: TranslationCache = globalTranslationCache) {
    this.cache = cache;
  }

  public setSimulateFailure(fail: boolean): void {
    this.shouldSimulateFailure = fail;
  }

  public async translate(
    text: string,
    targetLang: string,
    sourceLang = 'en'
  ): Promise<TranslationResult> {
    if (this.shouldSimulateFailure) {
      throw new Error(`Simulated translation failure for language: ${targetLang}`);
    }

    const lang = targetLang.toLowerCase().trim();
    if (lang === 'en' || !text.trim()) {
      return { translatedText: text, isTranslated: false, sourceLanguage: sourceLang };
    }

    const norm = text.trim().toLowerCase();

    // Check curated match
    for (const [key, langMap] of Object.entries(CURATED_ARTICLE_TRANSLATIONS)) {
      if (norm.includes(key) || key.includes(norm)) {
        if (langMap[lang]) {
          return {
            translatedText: langMap[lang].title,
            isTranslated: true,
            sourceLanguage: sourceLang,
          };
        }
      }
    }

    // Generic dictionary-assisted translation
    let translated = text;
    for (const [enWord, transMap] of Object.entries(DICTIONARY_WORDS)) {
      if (transMap[lang]) {
        const regex = new RegExp(`\\b${enWord}\\b`, 'gi');
        translated = translated.replace(regex, transMap[lang]);
      }
    }

    // High-accuracy multilingual engine translation for all 10 Indian languages
    const validIndianLangs: IndianLanguage[] = [
      'hi',
      'te',
      'ta',
      'bn',
      'mr',
      'gu',
      'kn',
      'ml',
      'pa',
      'ur',
    ];
    if (validIndianLangs.includes(lang as IndianLanguage)) {
      translated = translateSentence(translated, lang as IndianLanguage);
    }

    const didTranslate = translated !== text;
    return {
      translatedText: translated,
      isTranslated: didTranslate,
      sourceLanguage: sourceLang,
    };
  }

  public async translateArticle(
    article: {
      id: string;
      title: string;
      description: string;
      content?: string;
    },
    targetLang: string
  ): Promise<TranslatedArticlePayload> {
    const lang = targetLang.toLowerCase().trim();

    // Return English original without translation overhead
    if (lang === 'en') {
      return {
        title: article.title,
        description: article.description,
        content: article.content,
        isTranslated: false,
        language: 'en',
        originalTitle: article.title,
        originalDescription: article.description,
        originalContent: article.content,
      };
    }

    // Check Cache by ID
    const cached = this.cache.get(article.id, lang);
    if (cached) {
      return cached;
    }

    // Check Cache by original title
    const cachedByTitle = this.cache.getByOriginalTitle?.(article.title, lang);
    if (cachedByTitle) {
      this.cache.set(article.id, lang, cachedByTitle);
      return cachedByTitle;
    }

    // Check curated match
    const normTitle = article.title.trim().toLowerCase();
    for (const [key, langMap] of Object.entries(CURATED_ARTICLE_TRANSLATIONS)) {
      if (normTitle.includes(key) || key.includes(normTitle)) {
        if (langMap[lang]) {
          const payload: TranslatedArticlePayload = {
            title: langMap[lang].title,
            description: langMap[lang].description,
            content: article.content
              ? `${langMap[lang].title}\n\n${langMap[lang].description}`
              : undefined,
            isTranslated: true,
            language: lang,
            originalTitle: article.title,
            originalDescription: article.description,
            originalContent: article.content,
          };
          this.cache.set(article.id, lang, payload);
          return payload;
        }
      }
    }

    // Attempt translation via multilingual engine
    try {
      const transTitle = await this.translate(article.title, lang);
      const transDesc = await this.translate(article.description, lang);
      const transContent = article.content
        ? (await this.translate(article.content, lang)).translatedText
        : undefined;

      const payload: TranslatedArticlePayload = {
        title: transTitle.translatedText,
        description: transDesc.translatedText,
        content: transContent,
        isTranslated: true,
        language: lang,
        originalTitle: article.title,
        originalDescription: article.description,
        originalContent: article.content,
      };

      this.cache.set(article.id, lang, payload);
      return payload;
    } catch {
      // Graceful fallback to original text with metadata
      return {
        title: article.title,
        description: article.description,
        content: article.content,
        isTranslated: false,
        language: 'en',
        originalTitle: article.title,
        originalDescription: article.description,
        originalContent: article.content,
      };
    }
  }

  public async translateArticlesBatch(
    articles: Array<{
      id: string;
      title: string;
      description: string;
      content?: string;
    }>,
    targetLang: string
  ): Promise<TranslatedArticlePayload[]> {
    return Promise.all(articles.map((art) => this.translateArticle(art, targetLang)));
  }
}

export const globalMockTranslator = new MockTranslator();

export function isCuratedArticleTitle(title: string): boolean {
  if (!title) return false;
  const normTitle = title.trim().toLowerCase();
  for (const key of Object.keys(CURATED_ARTICLE_TRANSLATIONS)) {
    if (normTitle.includes(key) || key.includes(normTitle)) {
      return true;
    }
  }
  return false;
}
