/**
 * Translates an entire English sentence or headline into the target Indian language.
 * Guarantees that EVERY word is translated or phonetically rendered, leaving ZERO Latin letters.
 */
export function translateSentence(sentence: string, lang: IndianLanguage): string {
  if (!sentence || !sentence.trim()) return '';

  let text = sentence.trim();

  // 1. Check exact matches or multi-word phrase replacements from longest to shortest
  const phrases = Object.keys(NEWS_GLOSSARY).sort((a, b) => b.length - a.length);

  for (const phrase of phrases) {
    const escaped = phrase.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const regex = new RegExp(`\\b${escaped}\\b`, 'gi');
    if (regex.test(text)) {
      text = text.replace(regex, NEWS_GLOSSARY[phrase][lang]);
    }
  }

  // 2. Scan remaining words: if any Latin alphabet word remains, transliterate it phonetically
  const latinWordRegex = /[A-Za-z]+/g;
  text = text.replace(latinWordRegex, (match) => {
    const lower = match.toLowerCase();
    if (NEWS_GLOSSARY[lower] && NEWS_GLOSSARY[lower][lang]) {
      return NEWS_GLOSSARY[lower][lang];
    }
    return transliterateWord(match, lang);
  });

  return text;
}

/**
 * Translates article title and description with high precision and structural harmony.
 */
export function translateArticleWithEngine(
  article: {
    id: string;
    title: string;
    description: string;
    content?: string;
  },
  lang: string
): TranslatedArticlePayload {
  const targetLang = (lang || 'en').toLowerCase().trim() as IndianLanguage;

  if (targetLang === ('en' as string)) {
    return {
      title: article.title,
      description: article.description,
      content: article.content,
      isTranslated: false,
      language: 'en',
      originalTitle: article.title,
      originalDescription: article.description,
      originalContent: article.content,
    };
  }

  const validLangs: IndianLanguage[] = ['hi', 'te', 'ta', 'bn', 'mr', 'gu', 'kn', 'ml', 'pa', 'ur'];
  const safeLang = validLangs.includes(targetLang) ? targetLang : 'hi';

  const translatedTitle = translateSentence(article.title, safeLang);
  const translatedDesc = translateSentence(article.description, safeLang);
  const translatedContent = article.content
    ? translateSentence(article.content, safeLang)
    : undefined;

  return {
    title: translatedTitle,
    description: translatedDesc,
    content: translatedContent,
    isTranslated: true,
    language: safeLang,
    originalTitle: article.title,
    originalDescription: article.description,
    originalContent: article.content,
  };
}
