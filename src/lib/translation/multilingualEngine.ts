/**
 * Phonetically transliterates an unrecognized English word into natural target Indian script.
 */
export function transliterateWord(word: string, lang: IndianLanguage): string {
  const clean = word.toLowerCase().replace(/[^a-z]/g, '');
  if (!clean) return word;

  let result = '';
  let i = 0;

  while (i < clean.length) {
    // Check 2-letter consonant clusters (sh, th, ch, ph, gh, kh, dh, bh, jh)
    const twoCons = clean.substring(i, i + 2);
    if (PHONETIC_CONSONANTS[twoCons]) {
      result += PHONETIC_CONSONANTS[twoCons][lang];
      i += 2;
      // Check following vowel
      if (i < clean.length) {
        const twoVowels = clean.substring(i, i + 2);
        if (PHONETIC_VOWELS[twoVowels]) {
          result += PHONETIC_VOWELS[twoVowels][lang];
          i += 2;
          continue;
        }
        const oneVowel = clean.substring(i, i + 1);
        if (PHONETIC_VOWELS[oneVowel]) {
          result += PHONETIC_VOWELS[oneVowel][lang];
          i += 1;
          continue;
        }
      }
      continue;
    }

    // Check 1-letter consonant
    const oneCons = clean.substring(i, i + 1);
    if (PHONETIC_CONSONANTS[oneCons]) {
      result += PHONETIC_CONSONANTS[oneCons][lang];
      i += 1;
      // Check following vowel
      if (i < clean.length) {
        const twoVowels = clean.substring(i, i + 2);
        if (PHONETIC_VOWELS[twoVowels]) {
          result += PHONETIC_VOWELS[twoVowels][lang];
          i += 2;
          continue;
        }
        const oneVowel = clean.substring(i, i + 1);
        if (PHONETIC_VOWELS[oneVowel]) {
          result += PHONETIC_VOWELS[oneVowel][lang];
          i += 1;
          continue;
        }
      }
      continue;
    }

    // Check standalone/initial vowel
    const twoVowels = clean.substring(i, i + 2);
    if (INITIAL_VOWELS[twoVowels]) {
      result += INITIAL_VOWELS[twoVowels][lang];
      i += 2;
      continue;
    }
    const oneVowel = clean.substring(i, i + 1);
    if (INITIAL_VOWELS[oneVowel]) {
      result += INITIAL_VOWELS[oneVowel][lang];
      i += 1;
      continue;
    }

    i++;
  }

  return result || word;
}

